// Theme color token interface
export interface ThemeColors {
  // Core
  background: string;
  foreground: string;
  surface: string;
  surfaceHover: string;
  border: string;
  borderHover: string;
  textPrimary: string;
  textSecondary: string;
  textMuted: string;
  accent: string;
  accentHover: string;

  // Accent extended
  accentText: string;
  accentBg: string;
  accentBgHover: string;

  // Semantic
  danger: string;
  dangerBg: string;
  success: string;
  successBg: string;
  warning: string;
  warningBg: string;

  // Team colors
  teamBlue: string;
  teamBlueBg: string;
  teamRed: string;
  teamRedBg: string;

  // Tier colors
  tierS: string;
  tierSBg: string;
  tierA: string;
  tierABg: string;
  tierB: string;
  tierBBg: string;
  tierC: string;
  tierCBg: string;

  // Score colors
  scoreHigh: string;
  scoreHighBg: string;
  scoreMid: string;
  scoreMidBg: string;
  scoreLow: string;
  scoreLowBg: string;
  scorePoor: string;
  scorePoorBg: string;

  // Chart colors
  chartGrid: string;
  chartAxis: string;
  chartTick: string;
  chartPrimary: string;
  chartSecondary: string;
  chartTooltipBg: string;
  chartTooltipBorder: string;

  // Selection
  selectionBg: string;
  selectionText: string;
}

export type ThemeCategory = "dark" | "light";

export interface ThemeDefinition {
  id: string;
  name: string;
  category: ThemeCategory;
  colors: ThemeColors;
}

